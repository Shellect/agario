#pragma once

#include "vector2d.hpp"

// Тема: абстрактный базовый класс и виртуальный деструктор.
//
// Entity задаёт контракт клетки мира: шаг симуляции, радиус, позиция.
// Чисто виртуальные функции (= 0) делают класс абстрактным. Объект «просто
// Entity» создать нельзя — в игре существуют только конкретные виды.
// Абстрактность заодно запрещает vector<Entity> и приём Entity по значению:
// такой объект нельзя сконструировать, значит и срезать наследника в копию
// базы случайно не получится.
//
// Виртуальный деструктор обязателен, потому что World хранит
// unique_ptr<Entity> и удаляет игрока и еду через указатель на базу.
// Удаление производного объекта через базу с невиртуальным деструктором —
// неопределённое поведение: деструктор наследника не вызовется, его поля
// не уничтожатся. Пустое тело (= default) эту обязанность не отменяет.
// Поля наследника уничтожаются именно деструктором наследника.
//
// intersects — обычный, не виртуальный метод. Ему хватает уже виртуальных
// radius() и position(). const и константная ссылка означают: столкновение
// только наблюдает клетки, не двигает их и не копирует. Копия срезала бы
// наследника, даже если бы база не была абстрактной.
//
// База намеренно не знает про сокеты и про сессию. Соединение и клетка живут
// в разном времени: TCP может оборваться раньше, чем клетку съели, и наоборот.
// Наследование игрока от сессии склеило бы эти шкалы.
class Entity {
public:
    virtual ~Entity() = default;

    virtual void update(float dt) = 0;
    virtual float radius() const = 0;
    virtual Vector2 position() const = 0;

    bool intersects(const Entity& other) const {
        const float reach = radius() + other.radius();
        return (position() - other.position()).length() < reach;
    }
};
